def _format_hits(hits: list[str]) -> str:
    """将命中项列表格式化为可读字符串。

    Args:
        hits: 命中项列表

    Returns:
        格式化后的字符串
    """
    if not hits:
        return "无特殊命中"
    return "、".join(hits)


def _select_template(dim_name: str, score: float) -> str:
    """根据维度名称和分数选择合适的文案模板。

    Args:
        dim_name: 维度名称
        score: 维度分数

    Returns:
        选中的文案模板
    """
    templates = INTERPRETATION_TEMPLATES.get(dim_name, {})
    if score >= 70:
        candidates = templates.get("high", ["该维度表现良好。"])
    elif score >= 40:
        candidates = templates.get("mid", ["该维度表现中等。"])
    else:
        candidates = templates.get("low", ["该维度表现欠佳。"])
    return random.choice(candidates)


def generate_interpretation(match_result: MatchResult) -> str:
    """生成合盘解读文案。

    Args:
        match_result: 匹配结果

    Returns:
        解读文案字符串
    """
    parts: list[str] = []

    # 1. 总评
    grade = match_result.grade
    grade_templates = GRADE_INTERPRETATIONS.get(grade, ["你们的八字匹配度一般。"])
    parts.append(random.choice(grade_templates))

    # 2. 各维度解读
    for dim in match_result.dimensions:
        template = _select_template(dim.name, dim.score)
        # 尝试格式化模板中的 {hits} 占位符
        try:
            interpreted = template.format(hits=_format_hits(dim.hits))
        except (KeyError, IndexError):
            interpreted = template
        parts.append(f"【{dim.name}】{interpreted}")

    # 3. 通用建议
    parts.append(random.choice(SUGGESTION_TEMPLATES))

    return "\n\n".join(parts)
